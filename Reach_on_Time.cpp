//Reach on Time
#include <bits/stdc++.h>

using namespace std;

int main() {
        int T;
        cin >> T;

        while (T--) {
            int X;
            cin >> X;
            if (X >= 30) {
                cout << "Yes" << endl;
            }
            else {
                cout << "No" << endl;
            }
        }
}
